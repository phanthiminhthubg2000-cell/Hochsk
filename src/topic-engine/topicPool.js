// ============================================================
// LỌC TOPIC THEO TRÌNH ĐỘ (Hỗ trợ cả "HSK 1" và "HSK1")
// ============================================================
export function getTopicsByLevel(level) {
  const normalizedLevel = level ? level.toString().trim() : "HSK 1";
  const altLevel = normalizedLevel.includes(" ") 
    ? normalizedLevel.replace(" ", "") 
    : normalizedLevel.replace("HSK", "HSK ");

  return topicPool.filter(topic =>
    topic.levels.includes(normalizedLevel) || topic.levels.includes(altLevel)
  );
}


// ============================================================
// LẤY TOPIC NGẪU NHIÊN (Có chống lặp situation + group)
// ============================================================
export function getRandomTopic(
  level = "HSK 1",
  recentTopics = [],
  recentGroups = []
) {
  let available = getTopicsByLevel(level);
  if (available.length === 0) available = topicPool;

  // 1. Loại các situation vừa sử dụng gần đây
  let unusedSituations = available.filter(
    topic => !recentTopics.includes(topic.situation)
  );

  if (unusedSituations.length > 0) {
    available = unusedSituations;
  }

  // 2. Ưu tiên group chưa xuất hiện gần đây
  let freshGroups = available.filter(
    topic => !recentGroups.includes(topic.group)
  );

  if (freshGroups.length > 0) {
    available = freshGroups;
  }

  // 3. Chọn ngẫu nhiên trong tập hợp đã lọc
  if (available.length > 0) {
    return available[Math.floor(Math.random() * available.length)];
  }

  return topicPool[Math.floor(Math.random() * topicPool.length)];
}


// ============================================================
// LẤY NHIỀU TOPIC KHÔNG TRÙNG NHAU
// ============================================================
export function getRandomTopics(
  level = "HSK 1",
  count = 10,
  recentTopics = [],
  recentGroups = []
) {
  const selected = [];
  let currentRecentTopics = [...recentTopics];
  let currentRecentGroups = [...recentGroups];

  for (let i = 0; i < count; i++) {
    const topic = getRandomTopic(
      level,
      currentRecentTopics,
      currentRecentGroups
    );

    if (!topic) continue;

    selected.push(topic);
    currentRecentTopics.push(topic.situation);
    currentRecentGroups.push(topic.group);
  }

  return selected;
}


